/// Builds a dictionary, converting every value to a `Variant`. One form for
/// all value types keeps the call sites uniform.
macro_rules! vd {
    ($($key:expr => $value:expr),* $(,)?) => {{
        let mut d = VarDictionary::new();
        $( d.set($key, &($value).to_variant()); )*
        d
    }};
}

struct SimExtension;

#[gdextension]
unsafe impl ExtensionLibrary for SimExtension {}

/// Converts a simulation vector to Godot's axes.
fn to_godot(v: [f64; 3]) -> Vector3 {
    Vector3::new(-v[1] as f32, v[2] as f32, -v[0] as f32)
}

/// Converts a ground-plane point of the simulation to Godot's axes at a
/// given height.
fn ground_to_godot(p: [f64; 2], height: f64) -> Vector3 {
    to_godot([p[0], p[1], height])
}

/// Converts a simulation orientation `[w, x, y, z]` to a Godot quaternion.
fn quat_to_godot(q: [f64; 4]) -> Quaternion {
    Quaternion::new(-q[2] as f32, q[3] as f32, -q[1] as f32, q[0] as f32)
}

fn gstr(s: &str) -> GString {
    GString::from(s)
}

/// What the bridge remembers about the running session for drawing. These
/// are copies of immutable data, not simulation state.
struct Loaded {
    car: CarParams,
    wheel_radius: [f64; 2],
    tire_width: [f64; 2],
    track: Track,
}


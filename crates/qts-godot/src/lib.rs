    /// The best-lap ghost: `time` is that lap's time in seconds (zero if
    /// there is none); `visible` is true while a run is in progress and the
    /// ghost has not finished its lap, and then `transform` and `wheels`
    /// are laid out like `car_transform` and `wheel_states`.
    /// The drift judge (D-114): `active` (the track has zones), live
    /// `angle` and `zone`, the `last_zone` result, `lap_so_far` and
    /// `zones_so_far`, and after each lap `serial`, `lap_total`,
    /// `lap_counted`, `best` and `zones` (one dictionary per corner).
    #[func]
    fn drift(&self) -> VarDictionary {
        let Some(host) = &self.host else {
            return VarDictionary::new();
        };
        let d = host.drift();
        let zone_dict = |z: &qts_sim::drift::ZoneScore| {
            vd! {
                "name" => gstr(&z.name),
                "total" => z.total,
                "line" => z.line,
                "angle" => z.angle,
                "style" => z.style,
                "penalty" => z.penalty.is_some(),
                "text" => gstr(&z.describe()),
            }
        };
        let mut zones: Array<VarDictionary> = Array::new();
        let (mut lap_total, mut lap_counted) = (0.0, false);
        if let Some(lap) = &d.last_lap {
            lap_total = lap.total;
            lap_counted = lap.counted;
            for z in &lap.zones {
                match z {
                    Some(z) => zones.push(&zone_dict(z)),
                    None => {
                        zones.push(&vd! { "name" => gstr("-"), "total" => 0.0, "missed" => true })
                    }
                }
            }
        }
        vd! {
            "active" => d.active,
            "angle" => d.angle_deg,
            "zone" => gstr(d.zone.as_deref().unwrap_or("")),
            "has_last_zone" => d.last_zone.is_some(),
            "last_zone" => d.last_zone.as_ref().map(zone_dict).unwrap_or_default(),
            "lap_so_far" => d.lap_so_far,
            "zones_so_far" => i64::from(d.zones_so_far),
            "serial" => i64::from(d.serial),
            "has_lap" => d.last_lap.is_some(),
            "lap_total" => lap_total,
            "lap_counted" => lap_counted,
            "best" => d.best_total.unwrap_or(-1.0),
            "coach" => gstr(d.coach.as_deref().unwrap_or("")),
            "zones" => zones,
        }
    }

    #[func]
    fn coach(&self) -> VarDictionary {
        // The coach's newest report (D-106): `serial` counts reports;
        // `corners` holds one dictionary per corner with `number`, `left`,
        // `time_lost`, `cause` (a key) and `text`.
        let Some(host) = &self.host else {
            return VarDictionary::new();
        };
        let slot = host.coach();
        let mut corners: Array<VarDictionary> = Array::new();
        let (lap_s, reference_s) = slot
            .report
            .as_ref()
            .map_or((0.0, 0.0), |r| (r.lap_s, r.reference_s));
        if let Some(r) = &slot.report {
            for c in &r.corners {
                corners.push(&vd! {
                    "number" => c.corner.number as i64,
                    "left" => c.corner.left,
                    "time_lost" => c.time_lost_s,
                    "cause" => gstr(c.cause.key()),
                    "text" => gstr(&c.cause.describe()),
                    "min_speed_kmh" => c.min_speed_kmh.0,
                    "ref_min_speed_kmh" => c.min_speed_kmh.1,
                });
            }
        }
        vd! {
            "serial" => i64::from(slot.serial),
            "has_report" => slot.report.is_some(),
            "lap_s" => lap_s,
            "reference_s" => reference_s,
            "corners" => corners,
            "error" => gstr(slot.error.as_deref().unwrap_or("")),
        }
    }

    #[func]
    fn ghost(&self) -> VarDictionary {
        let Some(host) = &self.host else {
            return VarDictionary::new();
        };
        let (pose, time) = host.ghost();
        let delta = host.ghost_delta();
        let score = host.ghost_score().unwrap_or(-1.0);
        let setup_name = Setup::from_text(&host.ghost_setup())
            .map(|s| s.display_name())
            .unwrap_or_default();
        let Some(pose) = pose else {
            return vd! {
                "visible" => false, "time" => time, "has_delta" => false, "delta" => 0.0,
                "setup" => gstr(&setup_name), "score" => score,
            };
        };
        let mut wheels = Vec::with_capacity(20);
        for w in &pose.wheels {
            let p = to_godot(w.center_body);
            wheels.extend_from_slice(&[p.x, p.y, p.z, w.steer_angle as f32, w.spin_angle as f32]);
        }
        vd! {
            "visible" => true,
            "time" => time,
            "score" => score,
            "setup" => gstr(&setup_name),
            "has_delta" => delta.is_some(),
            "delta" => delta.unwrap_or(0.0),
            "transform" => Transform3D::new(
                Basis::from_quaternion(quat_to_godot(pose.rot)),
                to_godot(pose.pos),
            ),
            "wheels" => PackedFloat32Array::from(wheels),
        }
    }

    /// Lets the computer drive the player's car (D-122): `mode` is "grip"
    /// or "drift", "" hands the car back. `pace` 0.3 to 1.
    #[func]
    fn set_ai_driver(&mut self, mode: GString, pace: f64) -> bool {
        let Some(host) = &self.host else {
            return false;
        };
        let config = match ai_config(&mode.to_string(), pace) {
            Ok(c) => c,
            Err(e) => {
                self.last_error = e;
                return false;
            }
        };
        host.send(HostCommand::SetAiDriver(config));
        true
    }

    /// Adds a computer-driven car on `car_id` (D-122), or removes it with
    /// `mode` "". `ahead_m` starts it that far ahead along the line, for a
    /// tandem lead. It has no assists and no contact with the player's car.
    #[func]
    fn set_opponent(&mut self, car_id: GString, mode: GString, pace: f64, ahead_m: f64) -> bool {
        if self.host.is_none() {
            return false;
        }
        let config = match ai_config(&mode.to_string(), pace) {
            Ok(Some(c)) => c,
            Ok(None) => {
                self.send_opponent(None);
                return true;
            }
            Err(e) => {
                self.last_error = e;
                return false;
            }
        };
        let Some(root) = self.root() else {
            return false;
        };
        let track_id = self
            .loaded
            .as_ref()
            .map(|l| l.track.def().id.clone())
            .unwrap_or_default();
        let made = Session::from_data(
            &root,
            &car_id.to_string(),
            &track_id,
            AiDriver::session_config(),
        )
        .and_then(|session| {
            let driver = AiDriver::new(session.track(), config)?;
            Ok(Opponent::new(session, driver, ahead_m))
        });
        match made {
            Ok(o) => {
                self.send_opponent(Some(Box::new(o)));
                true
            }
            Err(e) => {
                self.last_error = e;
                false
            }
        }
    }


#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn axis_conversion_is_a_proper_rotation() {
        let fwd = to_godot([1.0, 0.0, 0.0]);
        let left = to_godot([0.0, 1.0, 0.0]);
        let up = to_godot([0.0, 0.0, 1.0]);
        assert_eq!(fwd, Vector3::new(0.0, 0.0, -1.0), "forward is -Z in Godot");
        assert_eq!(left, Vector3::new(-1.0, 0.0, 0.0), "left is -X in Godot");
        assert_eq!(up, Vector3::new(0.0, 1.0, 0.0), "up is +Y in Godot");
        // Right-handedness is preserved: forward x left = up.
        assert_eq!(fwd.cross(left), up);
    }

    #[test]
    fn a_left_yaw_stays_a_left_yaw() {
        // 90 degrees to the left about the simulation's z axis.
        let h = std::f64::consts::FRAC_PI_4;
        let q = quat_to_godot([h.cos(), 0.0, 0.0, h.sin()]);
        // In Godot that is a rotation about +Y.
        assert!((q.y - h.sin() as f32).abs() < 1e-6);
        assert!(q.x.abs() < 1e-6 && q.z.abs() < 1e-6);
        assert!((q.w - h.cos() as f32).abs() < 1e-6);
    }
}

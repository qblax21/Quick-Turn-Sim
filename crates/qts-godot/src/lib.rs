    /// What a setup does in physical terms (D-107): wheel rates, ride
    /// frequencies, damping ratios, roll stiffness and split, differential
    /// locking. One `label: value` string per line; empty with
    /// `last_error` set if the setup is not valid.
    #[func]
    fn setup_summary(&mut self, car_id: GString, values: VarDictionary) -> PackedStringArray {
        let setup = setup_from_dict("", &values);
        let result = self
            .car_and_tires(&car_id.to_string())
            .and_then(|(c, f, r)| qts_sim::setup::setup_summary(&c, &f, &r, &setup));
        match result {
            Ok(lines) => lines
                .iter()
                .map(|(l, v)| GString::from(format!("{l}: {v}").as_str()))
                .collect(),
            Err(e) => {
                self.last_error = e;
                PackedStringArray::new()
            }
        }
    }

    /// Writes a setup sheet (D-107) to `sheets/` in the setup folder and
    /// returns its path, or an empty string with `last_error` set.
    #[func]
    fn setup_sheet_export(
        &mut self,
        car_id: GString,
        track_id: GString,
        name: GString,
        values: VarDictionary,
    ) -> GString {
        let (car, track) = (car_id.to_string(), track_id.to_string());
        let setup = setup_from_dict(&name.to_string(), &values);
        let file = setup_file_name(&setup.display_name())
            .map(|f| f.replace(".setup", ".txt"))
            .unwrap_or_else(|| "unnamed.txt".into());
        let Some(dir) = self.setup_dir.clone() else {
            self.last_error = "no setup folder".into();
            return GString::new();
        };
        let safe = |s: &str| s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
        if !safe(&car) || !safe(&track) {
            self.last_error = "bad car or track id".into();
            return GString::new();
        }
        let path = dir.join("sheets").join(format!("{car}_{track}_{file}"));
        let result = self.car_and_tires(&car).and_then(|(c, f, r)| {
            let sheet = qts_sim::setup::setup_sheet(&c, &f, &r, &setup, &track)?;
            std::fs::create_dir_all(path.parent().unwrap()).map_err(|e| e.to_string())?;
            std::fs::write(&path, sheet).map_err(|e| format!("{}: {e}", path.display()))
        });
        match result {
            Ok(()) => GString::from(path.display().to_string().as_str()),
            Err(e) => {
                self.last_error = e;
                GString::new()
            }
        }
    }

    /// Reads a setup sheet (or any setup file) for a car: `name` and
    /// `values`, or an empty dictionary with `last_error` set if it cannot
    /// be read or does not fit the car.
    #[func]
    fn setup_from_sheet(&mut self, car_id: GString, path: GString) -> VarDictionary {
        let path = path.to_string();
        let parsed = std::fs::read_to_string(&path)
            .map_err(|e| format!("{path}: {e}"))
            .and_then(|t| Setup::from_text(&t));
        let checked = parsed.and_then(|s| self.check_setup(&car_id.to_string(), &s).map(|()| s));
        match checked {
            Ok(s) => setup_to_dict(&s),
            Err(e) => {
                self.last_error = e;
                VarDictionary::new()
            }
        }
    }

    /// Every adjustment the garage offers for a car: `key`, `group`,
    /// `label`, `unit`, `min`, `max`, `step` and `default` (the value in the
    /// car's data file).
    #[func]
    fn setup_items(&mut self, car_id: GString) -> Array<VarDictionary> {
        let mut out = Array::new();
        let Some(root) = self.root() else {
            return out;
        };
        let car = match root.load_car(&car_id.to_string()) {
            Ok(c) => c.value,
            Err(e) => {
                self.last_error = e.to_string();
                return out;
            }
        };
        let tires = root
            .load_tire(&car.tire_front)
            .and_then(|f| root.load_tire(&car.tire_rear).map(|r| (f.value, r.value)));
        let (front, rear) = match tires {
            Ok(t) => t,
            Err(e) => {
                self.last_error = e.to_string();
                return out;
            }
        };
        for item in setup_items(&car, &front, &rear) {
            out.push(&vd! {
                "key" => gstr(&item.key),
                "group" => gstr(item.group),
                "label" => gstr(&item.label),
                "unit" => gstr(item.unit),
                "min" => item.min,
                "max" => item.max,
                "step" => item.step,
                "default" => item.default,
            });
        }
        out
    }

    /// The clutch pedal curve of a car with the setup chosen for the next
    /// session: `free_travel`, `bite_point`, `bite_width`, `release` (pedal
    /// travel, 0 to 1) and `curve`, the engagement at 101 even steps of
    /// travel. Empty for a car without a clutch.
    #[func]
    fn clutch_curve(&mut self, car_id: GString) -> VarDictionary {
        let Some(root) = self.root() else {
            return VarDictionary::new();
        };
        let loaded = root.load_car(&car_id.to_string()).and_then(|c| {
            let front = root.load_tire(&c.value.tire_front)?.value;
            let rear = root.load_tire(&c.value.tire_rear)?.value;
            Ok((c.value, front, rear))
        });
        let (mut car, mut front, mut rear) = match loaded {
            Ok(t) => t,
            Err(e) => {
                self.last_error = e.to_string();
                return VarDictionary::new();
            }
        };
        // The garage setup may move the bite point; fall back to the car
        // as delivered if it does not fit this car.
        let plain = car.clone();
        if self
            .next_setup
            .apply(&mut car, &mut front, &mut rear)
            .is_err()
        {
            car = plain;
        }
        let DrivetrainParams::EngineManual(m) = &car.drivetrain else {
            return VarDictionary::new();
        };
        let cl = &m.clutch;
        let curve: PackedFloat32Array = (0..=100)
            .map(|i| cl.engagement(f64::from(i) / 100.0) as f32)
            .collect();
        vd! {
            "free_travel" => cl.free_travel,
            "bite_point" => cl.bite_point,
            "bite_width" => cl.bite_width,
            "release" => cl.release_travel(),
            "curve" => curve,
        }
    }

    /// Names of the setups saved for a car and track.
    #[func]
    fn setup_list(&self, car_id: GString, track_id: GString) -> PackedStringArray {
        let mut names: Vec<String> = Vec::new();
        if let Some(dir) = self.setup_folder(&car_id.to_string(), &track_id.to_string()) {
            if let Ok(entries) = std::fs::read_dir(dir) {
                for e in entries.flatten() {
                    let path = e.path();
                    if path.extension().is_some_and(|x| x == "setup") {
                        if let Some(stem) = path.file_stem() {
                            names.push(stem.to_string_lossy().into_owned());
                        }
                    }
                }
            }
        }
        names.sort();
        names.iter().map(|n| gstr(n)).collect()
    }


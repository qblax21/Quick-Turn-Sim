//! Thin GDExtension binding between the Godot front end and the simulation.
//!
//! This crate converts types and axes and nothing else. It holds no
//! simulation state and makes no simulation decisions: sessions, timing,
//! force feedback and recording all live in `qts-sim` and below. The front
//! end sends inputs and reads poses and values to draw.
//!
//! # Axes
//!
//! The simulation uses x forward, y left, z up. Godot uses x right, y up,
//! and −z forward. The conversion is a proper rotation:
//! `godot = (−sim.y, sim.z, −sim.x)`. It is applied in [`to_godot`] and
//! [`quat_to_godot`], and nowhere else in the project.
//!
//! The GDExtension entry point is the only `unsafe` in this crate; the
//! binding framework requires the marker impl to be `unsafe`.
#![allow(unsafe_code)]
// Raised inside code generated by the binding framework for `SimBridge`.
#![allow(clippy::redundant_field_names)]


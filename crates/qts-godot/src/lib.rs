    /// The given points moved vertically onto the shaped ground (road and
    /// terrain, without kerb ridges or roughness). For drawing only.
    #[func]
    fn ground_heights(&self, points: PackedVector3Array) -> PackedVector3Array {
        let Some(l) = &self.loaded else {
            return points;
        };
        points
            .as_slice()
            .iter()
            .map(|p| {
                // Godot (x, y, z) is simulation (-y, z, -x).
                let (x, y) = (-f64::from(p.z), -f64::from(p.x));
                Vector3::new(p.x, l.track.ground_height(x, y) as f32, p.z)
            })
            .collect()
    }

    /// Height of the surface the tires roll on at each point (x and z
    /// kept, y replaced): the shaped ground plus kerbs and ridges, without
    /// the fine roughness.
    #[func]
    fn surface_heights(&self, points: PackedVector3Array) -> PackedVector3Array {
        let Some(l) = &self.loaded else {
            return points;
        };
        points
            .as_slice()
            .iter()
            .map(|p| {
                let (x, y) = (-f64::from(p.z), -f64::from(p.x));
                let (_, ridge) = l.track.surface_at(x, y);
                Vector3::new(p.x, (l.track.ground_height(x, y) + ridge) as f32, p.z)
            })
            .collect()
    }

